#!/usr/bin/env bash
# microG in place of Google Play services on a GSI image copy (devlog 2026-10-17).
#
# - services.jar gets microg/MicrogSpoofFix.java: ComputerEngine.generatePackageInfo reports
#   com.google.android.gms and com.android.vending as signed with Google's key when they are
#   signed with microG's and ask for it, as LineageOS 20 does. Its odex, vdex and art are
#   replaced from gsi/odex-cache/services-<dex key> (scripts/services-odex.sh) when that
#   exists and removed otherwise, since the ones in the image no longer match.
# - microG Services (GmsCore) and microG Companion (com.android.vending) become priv-apps;
#   GmsCore's arm64 libraries are stored compressed, so they go next to it in lib/arm64.
#   Their privileged permissions are allowlisted, microg/default-permissions-microg.xml
#   grants a few runtime ones, and microg/sysconfig-microg.xml exempts GmsCore from Doze
#   and Data Saver so push messages arrive.
# - Aurora Store (anonymous Google Play downloads) becomes an ordinary system app, so it can
#   update itself. F-Droid was here until 10-19; the user dropped it so owners get one store.
#
# The APKs are downloaded once into tools/microg-dl/ and checked by sha256; microG's two are
# also checked for microG's release key, the one the spoofing accepts.
#
# Usage: scripts/microg-gsi.sh <in.img> <out.img>

set -euo pipefail
IN="$1"
OUT="$2"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
BT="$ROOT/tools/build-tools-dl/x/android-14"
DEXLIB2="$ROOT/tools/dexlib2-dl/dexlib2-2.5.2.jar:$ROOT/tools/dexlib2-dl/guava-27.1-android.jar"
DL="$ROOT/tools/microg-dl"
PART_BYTES=3145728000 # system_b
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

SVC=/system/framework/services.jar
SVC_OAT=/system/framework/oat/arm64/services
MICROG_CERT=9bd06727e62796c0130eb6dab39b73157451582cbd138e86c468acc395d14165
GH=https://github.com/microg/GmsCore/releases/download/v0.3.17.252432
FD=https://f-droid.org/repo
# image path, download, sha256
APKS=(
	"/system/priv-app/GmsCore/GmsCore.apk $GH/com.google.android.gms-252432034.apk e5e6cba078bdec812b5450599350e5c1a12c8b7438da5bf77123af170f8c1a35"
	"/system/priv-app/MicrogCompanion/MicrogCompanion.apk $GH/com.android.vending-84022634.apk 9b8616011cc8f026bcbbe094df850794abb9d6d9f23214d7a8f8c4d1033ea012"
	"/system/app/AuroraStore/AuroraStore.apk $FD/com.aurora.store_76.apk fd9c75d90d0f4a7c132b9b4a5a2cf1992a45e03b8d8ff988b7dcfbc0db2c4d11"
)
PRIV_XML=/system/etc/permissions/privapp-permissions-microg.xml
DEF_XML=/system/etc/default-permissions/default-permissions-microg.xml
SYS_XML=/system/etc/sysconfig/microg.xml

cp --reflink=auto "$IN" "$OUT"
printf '%s\0' u:object_r:system_file:s0 >"$WORK/ctx-system"

mkdir -p "$DL"
for a in "${APKS[@]}"; do
	read -r path url sha <<<"$a"
	f="$DL/$(basename "$url")"
	[ -s "$f" ] || curl -sSfL -o "$f" "$url"
	[ "$(sha256sum "$f" | cut -d' ' -f1)" = "$sha" ] || { echo "$f: unexpected sha256" >&2; exit 1; }
	if [[ $path == /system/priv-app/* ]]; then
		"$BT/apksigner" verify --print-certs "$f" 2>/dev/null |
			grep -qx "Signer #1 certificate SHA-256 digest: $MICROG_CERT" ||
			{ echo "$f: not signed with microG's release key" >&2; exit 1; }
	fi
	if debugfs -R "stat $(dirname "$path")" "$OUT" 2>/dev/null | grep -q '^Inode:'; then
		echo "$IN: $(dirname "$path") already exists" >&2
		exit 1
	fi
done

debugfs -R "dump $SVC $WORK/services.jar" "$OUT" 2>/dev/null
java -Xmx3g -cp "$DEXLIB2:$BT/lib/d8.jar" "$ROOT/microg/MicrogSpoofFix.java" \
	"$WORK/services.jar" "$ROOT/microg/ZxMicrogSpoof.java" "$WORK/services-unaligned.jar"
"$BT/zipalign" -p -f 4 "$WORK/services-unaligned.jar" "$WORK/services-patched.jar"
KEY=$(env -u PYTHONHOME -u PYTHONPATH /usr/bin/python3 -I "$ROOT/scripts/dex-key.py" "$WORK/services-patched.jar")
ODEX="$ROOT/gsi/odex-cache/services-$KEY"
if [ ! -s "$ODEX/services.odex" ]; then
	echo "no $ODEX: services.jar runs without odex (see scripts/services-odex.sh)" >&2
	ODEX=
fi

GMS="$DL/com.google.android.gms-252432034.apk"
mkdir "$WORK/gmslib"
unzip -q -j "$GMS" 'lib/arm64-v8a/*.so' -d "$WORK/gmslib"

{
	echo '<?xml version="1.0" encoding="utf-8"?>'
	echo '<!-- Generated by scripts/microg-gsi.sh from the apps'"'"' own manifests. -->'
	echo '<permissions>'
	for a in "${APKS[@]:0:2}"; do
		read -r path url sha <<<"$a"
		f="$DL/$(basename "$url")"
		echo "    <privapp-permissions package=\"$("$BT/aapt2" dump packagename "$f")\">"
		"$BT/aapt2" dump permissions "$f" |
			sed -n "s/^uses-permission: name='\([^']*\)'.*/        <permission name=\"\1\"\/>/p" |
			sort -u
		echo "    </privapp-permissions>"
	done
	echo '</permissions>'
} >"$WORK/privapp.xml"

dir() {
	cat <<EOF
mkdir $1
sif $1 mode 040755
ea_set -f $WORK/ctx-system $1 security.selinux
EOF
}
file() {
	cat <<EOF
write $1 $2
sif $2 mode 0100644
sif $2 uid 0
sif $2 gid 0
ea_set -f $WORK/ctx-system $2 security.selinux
EOF
}
{
	echo "rm $SVC"
	file "$WORK/services-patched.jar" $SVC
	for x in odex vdex art; do
		# An earlier step without a cached odex already took them out.
		if debugfs -R "stat $SVC_OAT.$x" "$OUT" 2>/dev/null | grep -q '^Inode:'; then
			echo "rm $SVC_OAT.$x"
		fi
		[ -z "$ODEX" ] || file "$ODEX/services.$x" "$SVC_OAT.$x"
	done
	for a in "${APKS[@]}"; do
		read -r path url sha <<<"$a"
		dir "$(dirname "$path")"
		file "$DL/$(basename "$url")" "$path"
	done
	dir /system/priv-app/GmsCore/lib
	dir /system/priv-app/GmsCore/lib/arm64
	for so in "$WORK"/gmslib/*.so; do
		file "$so" "/system/priv-app/GmsCore/lib/arm64/$(basename "$so")"
	done
	file "$WORK/privapp.xml" $PRIV_XML
	dir "$(dirname $DEF_XML)"
	file "$ROOT/microg/default-permissions-microg.xml" $DEF_XML
	file "$ROOT/microg/sysconfig-microg.xml" $SYS_XML
} >"$WORK/cmds"

truncate -s "$PART_BYTES" "$OUT"
resize2fs "$OUT" >/dev/null
debugfs -w -f "$WORK/cmds" "$OUT" >"$WORK/debugfs.log" 2>&1
if grep -vE '^(debugfs [0-9.]+ \(|debugfs: |Allocated inode: [0-9]+$|$)' "$WORK/debugfs.log" | grep -q .; then
	cat "$WORK/debugfs.log" >&2
	exit 1
fi
e2fsck -fn "$OUT" >/dev/null
resize2fs -M "$OUT" >/dev/null
blocks=$(dumpe2fs -h "$OUT" 2>/dev/null | awk -F: '/^Block count/{gsub(/ /,"",$2); print $2}')
truncate -s $((blocks * 4096)) "$OUT"
e2fsck -fn "$OUT" >/dev/null
echo "$OUT: microG (signature spoofing in services.jar${ODEX:+ + odex}), Aurora Store"

#!/usr/bin/env bash
# Add the unit's own Sony apps and their native libraries to a GSI image copy.
#
# Everything comes from the operator's own stock system.img and stays on this
# machine. The APKs are re-signed with AOSP's public platform test key, which
# is what TrebleDroid's framework-res is signed with, so the apps that share
# android.uid.system install and all of them are exempt from hidden-API
# enforcement. A privapp-permissions file allowlists every permission the
# priv-apps request.
#
# Eight of the apps were shipped stripped: their only code is CompactDex inside
# the Android 9 oat/arm64/<name>.vdex, which a newer ART rejects.
# scripts/VdexToDex.java turns it back into standard, unquickened dex
# (needs java and dexlib2 2.5.2 + guava 27.1-android in tools/dexlib2-dl).
#
# Not included: the system updater (it would install Sony's Android 9 OTAs),
# the in-store demo, the setup-wizard hook, Sony's Settings and SystemUI.
# W.music's AudioTrack shim and its Bluetooth bytecode patch are separate steps.
#
# Usage: scripts/add-sony-apps.sh <in.img> <out.img> <stock-system.img> <build-tools-dir>

set -euo pipefail
IN="$1"
OUT="$2"
STOCK="$3"
BT="$4"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
KEYS="$ROOT/tools/aosp-testkeys"
DEXLIB2="$ROOT/tools/dexlib2-dl/dexlib2-2.5.2.jar:$ROOT/tools/dexlib2-dl/guava-27.1-android.jar"
PART_BYTES=3145728000 # system_b
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

PRIV_APPS="AudioInfoExtractor HighResMediaPlayerApp IzmAudioManager IzmDeviceManager StorageMonitorService"
APPS="BatteryCtrlService FuncCore HighQualitySoundGuideApp ReginfoViewApp SonyEulaApp SoundEffectApp VolumeCtrlAlert VolumeCtrlPanelApp"
LIBS="libspmedia_walkman.so libspmedia_walkman_ex.so libspusb_walkman.so libwmmediaplayer_walkman.so
libcnpysort.so libpinyin_convert.so lib_wma10_dec.so lib_wma10_dec_v2_arm12_elinux.so
lib_wma10d_wrap_arm12_elinux_android.so izm.android.properties@1.0.so"
XML=/system/etc/permissions/privapp-permissions-sony-walkman.xml

printf '%s\0' u:object_r:system_file:s0 >"$WORK/ctx-system"
printf '%s\0' u:object_r:system_lib_file:s0 >"$WORK/ctx-lib"

sign() {
	local src="$1" dst="$2"
	"$BT/zipalign" -p -f 4 "$src" "$WORK/aligned.apk"
	"$BT/apksigner" sign --key "$KEYS/platform.pk8" --cert "$KEYS/platform.x509.pem" \
		--out "$dst" "$WORK/aligned.apk"
	"$BT/apksigner" verify "$dst"
}

: >"$WORK/cmds"
{
	echo '<?xml version="1.0" encoding="utf-8"?>'
	echo '<!-- Generated by scripts/add-sony-apps.sh from the apps'"'"' own manifests. -->'
	echo '<permissions>'
} >"$WORK/privapp.xml"

add_app() {
	local part="$1" name="$2"
	local apk="$WORK/$name.apk"
	debugfs -R "dump /system/$part/$name/$name.apk $WORK/$name.orig.apk" "$STOCK" 2>/dev/null
	[ -s "$WORK/$name.orig.apk" ] || { echo "missing $part/$name in stock image" >&2; exit 1; }
	if ! unzip -Z1 "$WORK/$name.orig.apk" | grep -cx classes.dex >/dev/null; then
		debugfs -R "dump /system/$part/$name/oat/arm64/$name.vdex $WORK/$name.vdex" "$STOCK" 2>/dev/null
		[ -s "$WORK/$name.vdex" ] || { echo "$part/$name has neither dex nor vdex" >&2; exit 1; }
		mkdir "$WORK/dex-$name"
		java -cp "$DEXLIB2" "$ROOT/scripts/VdexToDex.java" "$WORK/$name.vdex" "$WORK/dex-$name"
		# zip stores each file's mtime in local time; a fixed one keeps rebuilds identical.
		touch -d 2008-01-01T00:00:00Z "$WORK/dex-$name"/classes*.dex
		TZ=UTC zip -q -j -X "$WORK/$name.orig.apk" "$WORK/dex-$name"/classes*.dex
	fi
	sign "$WORK/$name.orig.apk" "$apk"
	cat >>"$WORK/cmds" <<EOF
mkdir /system/$part/$name
sif /system/$part/$name mode 040755
ea_set -f $WORK/ctx-system /system/$part/$name security.selinux
write $apk /system/$part/$name/$name.apk
sif /system/$part/$name/$name.apk mode 0100644
sif /system/$part/$name/$name.apk uid 0
sif /system/$part/$name/$name.apk gid 0
ea_set -f $WORK/ctx-system /system/$part/$name/$name.apk security.selinux
EOF
	if [ "$part" = priv-app ]; then
		local pkg
		pkg=$("$BT/aapt2" dump packagename "$apk")
		echo "    <privapp-permissions package=\"$pkg\">" >>"$WORK/privapp.xml"
		"$BT/aapt2" dump permissions "$apk" |
			sed -n "s/^uses-permission: name='\([^']*\)'.*/        <permission name=\"\1\"\/>/p" |
			sort -u >>"$WORK/privapp.xml"
		echo "    </privapp-permissions>" >>"$WORK/privapp.xml"
	fi
}

for a in $PRIV_APPS; do add_app priv-app "$a"; done
for a in $APPS; do add_app app "$a"; done
echo '</permissions>' >>"$WORK/privapp.xml"

for d in lib64 lib; do
	for l in $LIBS; do
		link=$(debugfs -R "stat /system/$d/$l" "$STOCK" 2>/dev/null |
			sed -n 's/^Fast link dest: "\(.*\)"$/\1/p')
		if [ -n "$link" ]; then
			echo "symlink /system/$d/$l $link" >>"$WORK/cmds"
		else
			debugfs -R "dump /system/$d/$l $WORK/$d-$l" "$STOCK" 2>/dev/null
			[ -s "$WORK/$d-$l" ] || { echo "missing $d/$l in stock image" >&2; exit 1; }
			cat >>"$WORK/cmds" <<EOF
write $WORK/$d-$l /system/$d/$l
sif /system/$d/$l mode 0100644
sif /system/$d/$l uid 0
sif /system/$d/$l gid 0
EOF
		fi
		echo "ea_set -f $WORK/ctx-lib /system/$d/$l security.selinux" >>"$WORK/cmds"
	done
done

cat >>"$WORK/cmds" <<EOF
write $WORK/privapp.xml $XML
sif $XML mode 0100644
sif $XML uid 0
sif $XML gid 0
ea_set -f $WORK/ctx-system $XML security.selinux
EOF

cp --reflink=auto "$IN" "$OUT"
truncate -s "$PART_BYTES" "$OUT"
resize2fs "$OUT" >/dev/null
debugfs -w -f "$WORK/cmds" "$OUT" >"$WORK/debugfs.log" 2>&1
if grep -vE '^(debugfs [0-9.]+ \(|debugfs: |Allocated inode: [0-9]+$|$)' "$WORK/debugfs.log" | grep -q .; then
	cat "$WORK/debugfs.log" >&2
	exit 1
fi
e2fsck -fn "$OUT" >/dev/null
resize2fs -M "$OUT" >/dev/null
blocks=$(dumpe2fs -h "$OUT" 2>/dev/null | awk -F: '/^Block count/{gsub(/ /,"",$2); print $2}')
truncate -s $((blocks * 4096)) "$OUT"
e2fsck -fn "$OUT" >/dev/null
cp "$WORK/privapp.xml" "${OUT%.img}.privapp.xml"
echo "$OUT: $((blocks * 4096)) bytes"
